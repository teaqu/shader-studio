// Regenerates src/test/e2e/triplet-signatures.ts from the real pipeline.
// Runs the cross-language agreement test, harvests the TRIPLET_SIGNATURES_JSON
// line it logs, and writes the generated module. The test itself only reads
// the file, so regeneration is always this explicit step — never automatic.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const uiDir = dirname(fileURLToPath(import.meta.url));
const outPath = join(uiDir, "..", "src", "test", "e2e", "triplet-signatures.ts");

// The test exits nonzero when signatures drift or are missing — that is the
// point of regeneration, so harvest its stdout either way.
let output;
try {
  output = execFileSync(
    "npx",
    [
      "vitest",
      "run",
      "--config",
      "vitest.browser.config.mts",
      "src/test/e2e/CorpusViaTransport.e2e.test.ts",
      "-t",
      "cross-pipeline agreement",
    ],
    { cwd: join(uiDir, ".."), encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
} catch (error) {
  output = error.stdout ?? "";
}

const marker = "TRIPLET_SIGNATURES_JSON:";
const line = output.split("\n").find((candidate) => candidate.includes(marker));
if (!line) {
  throw new Error("agreement test logged no TRIPLET_SIGNATURES_JSON line");
}
const signatures = JSON.parse(line.slice(line.indexOf(marker) + marker.length));
const entries = Object.entries(signatures)
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([name, signature]) => `  ${JSON.stringify(name)}: ${JSON.stringify(signature)},`)
  .join("\n");
writeFileSync(
  outPath,
  `// GENERATED by \`npm run test:e2e:update-signatures -w ui\`. Do not edit by hand.\nexport const tripletSignatures: Record<string, string> = {\n${entries}\n};\n`,
);
console.log(`wrote ${Object.keys(signatures).length} signatures to ${outPath}`);
